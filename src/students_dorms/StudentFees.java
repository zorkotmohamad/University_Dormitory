    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        PrinterJob printerJob = PrinterJob.getPrinterJob();
    
    // Set the printable content
    printerJob.setPrintable(new Printable() {
        @Override
        public int print(Graphics g, PageFormat pf, int page) throws PrinterException {
            if (page > 0) {
                return NO_SUCH_PAGE;
            }
            
            // Translate the Graphics to account for margins
            Graphics2D g2d = (Graphics2D) g;
            g2d.translate(pf.getImageableX(), pf.getImageableY());
            
            // Set font and title for the bill
            g2d.setFont(new Font("Serif", Font.BOLD, 36)); // Big title font
            g2d.drawString("Students_Dorm", 180, 100); // Title centered (adjust coordinates for better positioning)

            // Set dashed line stroke
            float[] dashPattern = {10, 10}; // Dash pattern (10pt dash, 10pt space)
            BasicStroke dashedStroke = new BasicStroke(1, BasicStroke.CAP_BUTT, BasicStroke.JOIN_MITER, 10, dashPattern, 0);
            g2d.setStroke(dashedStroke);
            
            // Draw a dashed line separator after the title
            g2d.drawLine(100, 110, 500, 110); // Horizontal dashed line below title
            
            // Set a smaller font for details
            g2d.setFont(new Font("Serif", Font.PLAIN, 16)); // Normal font for details

            // Fetch the first row's invoice ID from jTable1 (assuming invoice ID is in the first column)
            String invoiceID = "";
            if (jTable1.getRowCount() > 0) {
                invoiceID = jTable1.getValueAt(0, 0).toString(); // Get the first invoice ID from jTable1
            } else {
                invoiceID = "N/A"; // Default value if there are no rows
            }

            // Print Student's details
            g2d.drawString("Student Bill", 100, 150);
            g2d.drawString("Invoice ID: " + invoiceID, 100, 170);
            g2d.drawString("Name: " + jTextField2.getText(), 100, 190);
            g2d.drawString("Email: " + jTextField3.getText(), 100, 210);
            g2d.drawString("Room Number: " + jTextField4.getText(), 100, 230);
            g2d.drawString("Month: " + jTextField5.getText(), 100, 250);
            g2d.drawString("Amount to be Paid: " + jTextField6.getText(), 100, 270);

            // Draw a dashed rectangle around the bill details
            g2d.drawRect(80, 120, 450, 170); // Draw a rectangle (x, y, width, height)
            
            // Set a normal stroke for the footer
            g2d.setStroke(new BasicStroke());
            
            // Footer
            g2d.setFont(new Font("Serif", Font.ITALIC, 12)); // Smaller italic font for footer
            g2d.drawString("Thank you for your payment!", 250, 320);

            return PAGE_EXISTS;
        }
    });
    
    // Show the print dialog and print if confirmed
    boolean doPrint = printerJob.printDialog();
    if (doPrint) {
        try {
            printerJob.print();
        } catch (PrinterException ex) {
            JOptionPane.showMessageDialog(null, "Printing failed: " + ex.getMessage());
        }
    }
    }//GEN-LAST:event_jButton5ActionPerformed

