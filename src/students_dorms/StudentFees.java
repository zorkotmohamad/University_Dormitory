    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String mobileNo = jTextField1.getText();
        SimpleDateFormat dformat = new SimpleDateFormat("MMM-yyyy");
        Date date = new Date();
        String month = dformat.format(date);
        try{
            Connection con = conn.getCon();
            Statement st = con.createStatement();
            ResultSet rs = st.executeQuery("select * from students where mobileNo='"+mobileNo+"' and status = 'Living'");
            if(rs.first()){
                //after searching a student
                jTextField1.setEditable(false);
                jTextField2.setText(rs.getString(2));
                jTextField3.setText(rs.getString(5));
                jTextField4.setText(rs.getString(8));
                jTextField5.setText(month);
                jTextField6.setText("200 "+"$");
            }
            else{
                JOptionPane.showMessageDialog(null,"Student does not exist");
                clear();
            }
            //to display all payment deatils
            tableDetails();
            //pour voir si l'etudiant a paye pour ce mois ou non
            ResultSet rs1 = st.executeQuery("select * from fees inner join students where students.status='Living' and fees.month='"+month+"' and fees.mobileNo='"+mobileNo+"' and students.mobileNo='"+mobileNo+"'");
            // means student payed
            if(rs1.first()){
                jButton3.setVisible(false);
                JOptionPane.showMessageDialog(null,"Fees already paid by the student for this month");
            }
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(null,e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

